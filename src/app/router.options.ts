import type {RouterConfig} from '@nuxt/schema'
import {defineNuxtRouteMiddleware} from '#imports'
import {useAuthStore} from '@/store/module/auth'

/**
 * Runs on the server and the client (the token lives in a cookie) and checks
 * the token on the API, not just its presence.
 */
const adminMiddleware = defineNuxtRouteMiddleware(async (to) => {
    const authStore = useAuthStore()
    const isAuthenticated = await authStore.initializeAuthenticate()

    if (!isAuthenticated) {
        return {name: 'login', query: {redirect: to.fullPath}}
    }
})

/**
 * Routes are declared manually (file based routing from `pages/` is not used),
 * the original routes generated by Nuxt are intentionally ignored.
 */
export default <RouterConfig>{
    routes: () => [
        {
            path: '/',
            component: () => import('~/layout/Main.vue'),
            children: [
                {
                    path: '',
                    name: 'home',
                    component: () => import('~/page/Home.vue')
                },
                {
                    path: 'products',
                    component: () => import('~/layout/Default.vue'),
                    children: [
                        {
                            path: '',
                            name: 'product_list',
                            component: () => import('~/page/Home.vue')
                        },
                        {
                            path: 'detail/:id(\\d+)',
                            name: 'product_detail',
                            meta: {title: 'Product detail'},
                            component: () => import('~/page/product/ProductDetail.vue')
                        }
                    ]
                },
                {
                    path: 'cart',
                    name: 'cart',
                    meta: {title: 'Shopping cart'},
                    component: () => import('~/page/cart/ShoppingCart.vue')
                },
                {
                    path: 'favorite',
                    name: 'favorite',
                    meta: {title: 'Favorite cart'},
                    component: () => import('~/page/favorite/FavoriteCart.vue')
                },
                {
                    path: 'order',
                    name: 'order',
                    meta: {title: 'Checkout cart'},
                    component: () => import('~/page/order/Order.vue')
                },
                {
                    path: 'order-thanks',
                    name: 'order_thanks',
                    meta: {title: 'Order thanks'},
                    component: () => import('~/page/order/OrderThanks.vue')
                },
                {
                    path: 'login',
                    name: 'login',
                    meta: {title: 'Login'},
                    component: () => import('~/page/admin/Authentication.vue')
                },
                {
                    path: 'admin',
                    name: 'admin',
                    redirect: {name: 'admin_product_list'},
                    meta: {middleware: [adminMiddleware]},
                    component: () => import('~/page/admin/Admin.vue'),
                    children: [
                        {
                            path: 'products/create',
                            name: 'admin_product_create',
                            meta: {title: 'Admin create product'},
                            component: () => import('~/page/admin/ProductEditor.vue')
                        },
                        {
                            path: 'products/edit/:id(\\d+)',
                            name: 'admin_product_edit',
                            meta: {title: 'Admin edit product'},
                            component: () => import('~/page/admin/ProductEditor.vue')
                        },
                        {
                            path: 'products',
                            name: 'admin_product_list',
                            meta: {title: 'Admin product list'},
                            component: () => import('~/page/admin/ProductAdmin.vue')
                        },
                        {
                            path: 'orders',
                            name: 'admin_order_list',
                            meta: {title: 'Admin order list'},
                            component: () => import('~/page/admin/OrderAdmin.vue')
                        }
                    ]
                },
                {
                    path: 'error',
                    name: 'error',
                    meta: {title: 'Error Page'},
                    component: () => import('~/page/Error404.vue')
                }
            ]
        },
        {
            path: '/:pathMatch(.*)*',
            redirect: '/error'
        }
    ]
}
